//! `PerAssetCnn` — burn-native reimplementation of the Python `PerAssetCNN`.
//!
//! This is the first model ported as part of the Python → Rust migration
//! (see fks-full `docs/architecture/RUST_MIGRATION.md`, Phase 2). It mirrors,
//! layer-for-layer, the champion architecture defined in the Python trainer at
//! `fks-full/src/ruby/src/ml/model.py` so that a `burn` model can serve the
//! same per-asset entry/exit signal at inference parity.
//!
//! # Architecture (inference path)
//!
//! ```text
//! input (B, n_features=20, window=60)
//!   AssetEncoder:
//!     block1  Conv1d(20→64,  k3, d1) → BatchNorm → +skip → ReLU → SE(64)
//!     block2  Conv1d(64→128, k3, d2) → BatchNorm → +skip → ReLU → SE(128)
//!     block3  Conv1d(128→64, k3, d4) → BatchNorm → +skip → ReLU → SE(64)
//!     block4  Conv1d(64→64,  k3, d8) → BatchNorm → +identity → ReLU → SE(64)
//!     globalavg ⊕ globalmax over time → (B, 128) → Linear(128→64, no bias) → ReLU
//!   head:
//!     [Dropout(0.4) — omitted at inference] → Linear(64→32) → ReLU → Linear(32→4)
//! output logits (B, n_classes=4)  →  softmax → [flat, long, short, loss]
//! ```
//!
//! Channels 64 and 128 are fixed (as in the Python model); blocks 3–4 use
//! `embedding_dim`. Dropout is a no-op at inference and is omitted here so the
//! forward pass is deterministic. BatchNorm uses its running statistics on the
//! non-autodiff [`CpuBackend`] (inference mode), matching PyTorch `.eval()`.
//!
//! # Parity
//!
//! [`reference_logits`] is an **independent** raw-`f32` implementation of the
//! same forward pass. The test suite asserts the `burn` modules agree with it
//! (differential testing — see `tests::burn_matches_reference`). The same
//! reference is the spec a PyTorch-vs-`burn` golden must satisfy; drop golden
//! files into `tests/golden/perasset_cnn/` (generated by
//! `tools/parity/record_perasset_cnn.py`) and `tests::pytorch_goldens` checks
//! them automatically.

