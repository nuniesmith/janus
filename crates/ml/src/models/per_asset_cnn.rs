use burn_core::module::{Param, RunningState};
use burn_core::tensor::{Tensor, TensorData, activation, backend::Backend};
use burn_nn::conv::{Conv1d, Conv1dConfig};
use burn_nn::{BatchNorm, BatchNormConfig, Linear, LinearConfig, PaddingConfig1d};
use serde::{Deserialize, Serialize};

use super::{ModelMetadata, ModelRecord, SerializedTensor, WeightMap};
use crate::error::{MLError, Result};
use std::path::Path;

/// Default input feature channels (must match `ml/features.py`).
pub const N_FEATURES: usize = 20;
/// Default output classes: flat / long / short / loss.
pub const N_CLASSES: usize = 4;
/// Default candle window length.
pub const DEFAULT_WINDOW: usize = 60;
/// Default encoder embedding width.
pub const DEFAULT_EMBEDDING_DIM: usize = 64;
/// BatchNorm epsilon — matches PyTorch / burn default.
const BN_EPS: f32 = 1e-5;

/// Configuration for [`PerAssetCnn`]. Mirrors the Python constructor args.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct PerAssetCnnConfig {
    /// Input feature channels.
    pub n_features: usize,
    /// Candle window length (architecture is window-agnostic via global pooling;
    /// kept for validation / metadata).
    pub window: usize,
    /// Output classes.
    pub n_classes: usize,
    /// Encoder embedding width.
    pub embedding_dim: usize,
}

impl Default for PerAssetCnnConfig {
    fn default() -> Self {
        Self {
            n_features: N_FEATURES,
            window: DEFAULT_WINDOW,
            n_classes: N_CLASSES,
            embedding_dim: DEFAULT_EMBEDDING_DIM,
        }
    }
}

impl PerAssetCnnConfig {
    /// Fixed first-block channel count (as in the Python model).
    const C1: usize = 64;
    /// Fixed second-block channel count (as in the Python model).
    const C2: usize = 128;
}

/// SE reduction divisor (channels / reduction, floored at 8).
fn se_mid(channels: usize) -> usize {
    (channels / 4).max(8)
}
/// 'same' padding for an odd kernel at a given dilation.
fn same_pad(kernel: usize, dilation: usize) -> usize {
    dilation * (kernel - 1) / 2
}

// ---------------------------------------------------------------------------
// Squeeze-and-Excitation block
// ---------------------------------------------------------------------------

#[derive(Debug)]
struct SeBlock<B: Backend> {
    fc1: Linear<B>, // (channels -> mid), no bias
    fc2: Linear<B>, // (mid -> channels), no bias
}

impl<B: Backend> SeBlock<B> {
    fn new(channels: usize, device: &B::Device) -> Self {
        let mid = se_mid(channels);
        Self {
            fc1: LinearConfig::new(channels, mid)
                .with_bias(false)
                .init(device),
            fc2: LinearConfig::new(mid, channels)
                .with_bias(false)
                .init(device),
        }
    }

    /// `x`: (batch, channels, time) → scaled (batch, channels, time).
    fn forward(&self, x: Tensor<B, 3>) -> Tensor<B, 3> {
        let [b, c, _l] = x.dims();
        let squeeze = x.clone().mean_dim(2).reshape([b, c]); // (b, c)
        let excite = activation::relu(self.fc1.forward(squeeze)); // (b, mid)
        let excite = activation::sigmoid(self.fc2.forward(excite)); // (b, c)
        x.mul(excite.reshape([b, c, 1])) // broadcast over time
    }
}

// ---------------------------------------------------------------------------
// Residual conv block: Conv1d → BatchNorm → (+ skip) → ReLU
// ---------------------------------------------------------------------------

#[derive(Debug)]
struct ConvBlock<B: Backend> {
    conv: Conv1d<B>,
    bn: BatchNorm<B>,
    /// 1×1 projection skip when in_channels != out_channels (else identity).
    skip: Option<Conv1d<B>>,
}

impl<B: Backend> ConvBlock<B> {
    fn new(
        in_channels: usize,
        out_channels: usize,
        kernel: usize,
        dilation: usize,
        device: &B::Device,
    ) -> Self {
        let conv = Conv1dConfig::new(in_channels, out_channels, kernel)
            .with_padding(PaddingConfig1d::Explicit(same_pad(kernel, dilation)))
            .with_dilation(dilation)
            .with_bias(false)
            .init(device);
        let bn = BatchNormConfig::new(out_channels).init(device);
        let skip = if in_channels != out_channels {
            Some(
                Conv1dConfig::new(in_channels, out_channels, 1)
                    .with_bias(false)
                    .init(device),
            )
        } else {
            None
        };
        Self { conv, bn, skip }
    }

    fn forward(&self, x: Tensor<B, 3>) -> Tensor<B, 3> {
        let main = self.bn.forward(self.conv.forward(x.clone()));
        let identity = match &self.skip {
            Some(skip) => skip.forward(x),
            None => x,
        };
        activation::relu(main.add(identity))
    }
}

// ---------------------------------------------------------------------------
// Asset encoder: 4 residual blocks (+SE) → dual global pool → projection
// ---------------------------------------------------------------------------

/// Shared convolutional backbone. Used by both [`PerAssetCnn`] and (via the
/// `super::master_cnn`) `MasterCnn`, mirroring the single `_AssetEncoder` class
/// reused by both Python models.
#[derive(Debug)]
pub(crate) struct AssetEncoder<B: Backend> {
    block1: ConvBlock<B>,
    se1: SeBlock<B>,
    block2: ConvBlock<B>,
    se2: SeBlock<B>,
    block3: ConvBlock<B>,
    se3: SeBlock<B>,
    block4: ConvBlock<B>,
    se4: SeBlock<B>,
    pool_proj: Linear<B>, // (2*emb -> emb), no bias
}

impl<B: Backend> AssetEncoder<B> {
    pub(crate) fn new(n_features: usize, embedding_dim: usize, device: &B::Device) -> Self {
        let (c1, c2) = (PerAssetCnnConfig::C1, PerAssetCnnConfig::C2);
        Self {
            block1: ConvBlock::new(n_features, c1, 3, 1, device),
            se1: SeBlock::new(c1, device),
            block2: ConvBlock::new(c1, c2, 3, 2, device),
            se2: SeBlock::new(c2, device),
            block3: ConvBlock::new(c2, embedding_dim, 3, 4, device),
            se3: SeBlock::new(embedding_dim, device),
            block4: ConvBlock::new(embedding_dim, embedding_dim, 3, 8, device),
            se4: SeBlock::new(embedding_dim, device),
            pool_proj: LinearConfig::new(embedding_dim * 2, embedding_dim)
                .with_bias(false)
                .init(device),
        }
    }

    pub(crate) fn forward(&self, x: Tensor<B, 3>) -> Tensor<B, 2> {
        let x = self.se1.forward(self.block1.forward(x));
        let x = self.se2.forward(self.block2.forward(x));
        let x = self.se3.forward(self.block3.forward(x));
        let x = self.se4.forward(self.block4.forward(x));
        let [b, c, _l] = x.dims();
        let avg = x.clone().mean_dim(2).reshape([b, c]);
        let max = x.max_dim(2).reshape([b, c]);
        let pooled = Tensor::cat(vec![avg, max], 1); // (b, 2c)
        activation::relu(self.pool_proj.forward(pooled)) // (b, emb)
    }

    /// Append the encoder's weights (keys prefixed `encoder.`) to `w`.
    pub(crate) fn extract_into(&self, w: &mut WeightMap) {
        let blocks = [
            (&self.block1, &self.se1, 1usize),
            (&self.block2, &self.se2, 2),
            (&self.block3, &self.se3, 3),
            (&self.block4, &self.se4, 4),
        ];
        for (block, se, i) in blocks {
            w.push(st3(
                &format!("encoder.block{i}.conv.weight"),
                &block.conv.weight.val(),
            ));
            w.push(st1(
                &format!("encoder.block{i}.bn.gamma"),
                &block.bn.gamma.val(),
            ));
            w.push(st1(
                &format!("encoder.block{i}.bn.beta"),
                &block.bn.beta.val(),
            ));
            w.push(st1(
                &format!("encoder.block{i}.bn.running_mean"),
                &block.bn.running_mean.value(),
            ));
            w.push(st1(
                &format!("encoder.block{i}.bn.running_var"),
                &block.bn.running_var.value(),
            ));
            if let Some(skip) = &block.skip {
                w.push(st3(
                    &format!("encoder.block{i}.skip.weight"),
                    &skip.weight.val(),
                ));
            }
            w.push(st2(
                &format!("encoder.se{i}.fc1.weight"),
                &se.fc1.weight.val(),
            ));
            w.push(st2(
                &format!("encoder.se{i}.fc2.weight"),
                &se.fc2.weight.val(),
            ));
        }
        w.push(st2(
            "encoder.pool_proj.weight",
            &self.pool_proj.weight.val(),
        ));
    }

    /// Overwrite the encoder's weights from a name→tensor map.
    pub(crate) fn apply(&mut self, map: &HashMap<&str, &SerializedTensor>, device: &B::Device) {
        let mut blocks = [
            (&mut self.block1, &mut self.se1, 1usize),
            (&mut self.block2, &mut self.se2, 2),
            (&mut self.block3, &mut self.se3, 3),
            (&mut self.block4, &mut self.se4, 4),
        ];
        for (block, se, i) in blocks.iter_mut() {
            let i = *i;
            set_conv(
                &mut block.conv,
                map.get(format!("encoder.block{i}.conv.weight").as_str()),
                device,
            );
            set_param1(
                &mut block.bn.gamma,
                map.get(format!("encoder.block{i}.bn.gamma").as_str()),
                device,
            );
            set_param1(
                &mut block.bn.beta,
                map.get(format!("encoder.block{i}.bn.beta").as_str()),
                device,
            );
            if let Some(st) = map.get(format!("encoder.block{i}.bn.running_mean").as_str()) {
                block.bn.running_mean = RunningState::new(t1(st, device));
            }
            if let Some(st) = map.get(format!("encoder.block{i}.bn.running_var").as_str()) {
                block.bn.running_var = RunningState::new(t1(st, device));
            }
            if let Some(skip) = block.skip.as_mut() {
                set_conv(
                    skip,
                    map.get(format!("encoder.block{i}.skip.weight").as_str()),
                    device,
                );
            }
            set_linear_w(
                &mut se.fc1,
                map.get(format!("encoder.se{i}.fc1.weight").as_str()),
                device,
            );
            set_linear_w(
                &mut se.fc2,
                map.get(format!("encoder.se{i}.fc2.weight").as_str()),
                device,
            );
        }
        set_linear_w(
            &mut self.pool_proj,
            map.get("encoder.pool_proj.weight"),
            device,
        );
    }
}

