/// Per-asset 1-D CNN signal classifier (`burn`-native).
#[derive(Debug)]
pub struct PerAssetCnn<B: Backend> {
    encoder: AssetEncoder<B>,
    head_fc1: Linear<B>, // (emb -> 32)
    head_fc2: Linear<B>, // (32 -> n_classes)
    config: PerAssetCnnConfig,
}

impl<B: Backend> PerAssetCnn<B> {
    /// Build a freshly-initialised model on `device`.
    pub fn new(config: PerAssetCnnConfig, device: &B::Device) -> Self {
        let encoder = AssetEncoder::new(config.n_features, config.embedding_dim, device);
        let head_fc1 = LinearConfig::new(config.embedding_dim, 32).init(device);
        let head_fc2 = LinearConfig::new(32, config.n_classes).init(device);
        Self {
            encoder,
            head_fc1,
            head_fc2,
            config,
        }
    }

    /// Model configuration.
    pub fn config(&self) -> &PerAssetCnnConfig {
        &self.config
    }

    /// Forward pass. `input`: (batch, n_features, window) → logits (batch, n_classes).
    pub fn forward(&self, input: Tensor<B, 3>) -> Tensor<B, 2> {
        let emb = self.encoder.forward(input);
        let hidden = activation::relu(self.head_fc1.forward(emb));
        self.head_fc2.forward(hidden)
    }

    /// Softmax class probabilities.
    pub fn predict_proba(&self, input: Tensor<B, 3>) -> Tensor<B, 2> {
        activation::softmax(self.forward(input), 1)
    }

    // -- weight extract / inject (burn-native layout) ------------------------

    /// Serialise every learnable tensor into a [`WeightMap`] (burn-native
    /// layout: Linear weights `[in, out]`, Conv weights `[out, in, k]`).
    pub fn extract_weights(&self) -> WeightMap {
        let mut w = Vec::new();
        self.encoder.extract_into(&mut w);
        w.push(st2("head.fc1.weight", &self.head_fc1.weight.val()));
        w.push(st1(
            "head.fc1.bias",
            &self.head_fc1.bias.as_ref().unwrap().val(),
        ));
        w.push(st2("head.fc2.weight", &self.head_fc2.weight.val()));
        w.push(st1(
            "head.fc2.bias",
            &self.head_fc2.bias.as_ref().unwrap().val(),
        ));
        w
    }

    /// Overwrite parameters from a [`WeightMap`] in burn-native layout.
    pub fn apply_weights(&mut self, weights: &WeightMap, device: &B::Device) {
        let map: HashMap<&str, &SerializedTensor> =
            weights.iter().map(|st| (st.name.as_str(), st)).collect();
        self.encoder.apply(&map, device);
        set_linear_w(&mut self.head_fc1, map.get("head.fc1.weight"), device);
        set_linear_b(&mut self.head_fc1, map.get("head.fc1.bias"), device);
        set_linear_w(&mut self.head_fc2, map.get("head.fc2.weight"), device);
        set_linear_b(&mut self.head_fc2, map.get("head.fc2.bias"), device);
    }

    /// Persist config + weights to `path` (postcard [`ModelRecord`]). This is
    /// how the forward service loads champions (mirrors `LstmPredictor`).
    pub fn save<P: AsRef<Path>>(&self, path: P) -> Result<()> {
        save_record(
            path.as_ref(),
            &self.config,
            &self.extract_weights(),
            "per_asset_cnn",
            self.config.n_features,
            self.config.n_classes,
        )
    }

    /// Load a model persisted by [`save`](Self::save).
    pub fn load<P: AsRef<Path>>(path: P, device: &B::Device) -> Result<Self> {
        let (config, weights) = load_record::<PerAssetCnnConfig>(path.as_ref())?;
        let mut model = Self::new(config, device);
        if !weights.is_empty() {
            model.apply_weights(&weights, device);
        }
        Ok(model)
    }
}

/// Persist a model as a postcard [`ModelRecord`] (config JSON + JSON weight
/// map). Shared by the burn CNN models so the forward service can load any of
/// them uniformly.
pub(crate) fn save_record<C: Serialize>(
    path: &Path,
    config: &C,
    weights: &WeightMap,
    name: &str,
    input_size: usize,
    output_size: usize,
) -> Result<()> {
    let weights_json = serde_json::to_vec(weights).map_err(|e| MLError::io_error(e.to_string()))?;
    let config_json = serde_json::to_string(config)?;
    let metadata = ModelMetadata::new(
        name.to_string(),
        env!("CARGO_PKG_VERSION").to_string(),
        name.to_string(),
        input_size,
        output_size,
        "cpu".to_string(),
    );
    let record = ModelRecord::new(metadata, config_json, weights_json);
    let bytes = postcard::to_allocvec(&record)?;
    std::fs::write(path, bytes)
        .map_err(|e| MLError::io_error(format!("failed to write {path:?}: {e}")))?;
    Ok(())
}

/// Load a `(config, weights)` pair persisted by [`save_record`].
pub(crate) fn load_record<C: serde::de::DeserializeOwned>(path: &Path) -> Result<(C, WeightMap)> {
    let bytes = std::fs::read(path)
        .map_err(|e| MLError::io_error(format!("failed to read {path:?}: {e}")))?;
    let record: ModelRecord<Vec<u8>> = postcard::from_bytes(&bytes)?;
    if !record.is_compatible() {
        return Err(MLError::invalid_config(format!(
            "incompatible model format version: {}",
            record.format_version
        )));
    }
    let config: C = serde_json::from_str(&record.config)?;
    let weights: WeightMap = if record.weights.is_empty() {
        Vec::new()
    } else {
        serde_json::from_slice(&record.weights)
            .map_err(|e| MLError::model_load(format!("failed to deserialise weights: {e}")))?
    };
    Ok((config, weights))
}

// ---------------------------------------------------------------------------
// Tensor (de)serialisation helpers
// ---------------------------------------------------------------------------

pub(crate) fn st1<B: Backend>(name: &str, t: &Tensor<B, 1>) -> SerializedTensor {
    SerializedTensor {
        name: name.into(),
        shape: t.dims().to_vec(),
        data: t.to_data().to_vec().unwrap(),
    }
}
pub(crate) fn st2<B: Backend>(name: &str, t: &Tensor<B, 2>) -> SerializedTensor {
    SerializedTensor {
        name: name.into(),
        shape: t.dims().to_vec(),
        data: t.to_data().to_vec().unwrap(),
    }
}
fn st3<B: Backend>(name: &str, t: &Tensor<B, 3>) -> SerializedTensor {
    SerializedTensor {
        name: name.into(),
        shape: t.dims().to_vec(),
        data: t.to_data().to_vec().unwrap(),
    }
}
fn t1<B: Backend>(st: &SerializedTensor, device: &B::Device) -> Tensor<B, 1> {
    Tensor::from_data(TensorData::new(st.data.clone(), [st.shape[0]]), device)
}
fn t2<B: Backend>(st: &SerializedTensor, device: &B::Device) -> Tensor<B, 2> {
    Tensor::from_data(
        TensorData::new(st.data.clone(), [st.shape[0], st.shape[1]]),
        device,
    )
}
fn t3<B: Backend>(st: &SerializedTensor, device: &B::Device) -> Tensor<B, 3> {
    Tensor::from_data(
        TensorData::new(st.data.clone(), [st.shape[0], st.shape[1], st.shape[2]]),
        device,
    )
}
fn set_conv<B: Backend>(conv: &mut Conv1d<B>, st: Option<&&SerializedTensor>, device: &B::Device) {
    if let Some(st) = st {
        conv.weight = Param::initialized(conv.weight.id, t3(st, device));
    }
}
pub(crate) fn set_linear_w<B: Backend>(
    lin: &mut Linear<B>,
    st: Option<&&SerializedTensor>,
    device: &B::Device,
) {
    if let Some(st) = st {
        lin.weight = Param::initialized(lin.weight.id, t2(st, device));
    }
}
pub(crate) fn set_linear_b<B: Backend>(
    lin: &mut Linear<B>,
    st: Option<&&SerializedTensor>,
    device: &B::Device,
) {
    if let (Some(bias), Some(st)) = (lin.bias.as_mut(), st) {
        *bias = Param::initialized(bias.id, t1(st, device));
    }
}
pub(crate) fn set_param1<B: Backend>(
    param: &mut Param<Tensor<B, 1>>,
    st: Option<&&SerializedTensor>,
    device: &B::Device,
) {
    if let Some(st) = st {
        *param = Param::initialized(param.id, t1(st, device));
    }
}

// ---------------------------------------------------------------------------
// Independent reference forward pass (raw f32) — the parity oracle
// ---------------------------------------------------------------------------

/// Independent, plain-`f32` reference for the shared [`AssetEncoder`]. Reads
/// weights (keys prefixed `encoder.`) from a name→tensor map and returns the
/// `embedding_dim`-length embedding for one `(n_features, window)` sample.
///
/// Written without the `burn` neural-network modules so that agreement with the
/// `burn` encoder is a genuine cross-check; reused by both [`reference_logits`]
/// and the MasterCnn reference, and the executable spec a PyTorch golden must
/// satisfy.
pub(crate) fn reference_encoder(
    map: &HashMap<&str, &SerializedTensor>,
    input: &[f32],
    n_features: usize,
    window: usize,
    embedding_dim: usize,
) -> Vec<f32> {
    let get = |name: &str| -> &SerializedTensor {
        map.get(name)
            .unwrap_or_else(|| panic!("missing weight {name}"))
    };

    let l = window;
    let emb = embedding_dim;
    let (c1, c2) = (PerAssetCnnConfig::C1, PerAssetCnnConfig::C2);

    // conv1d (stride 1, zero pad, dilation) — w: [out,in,k]; x: (in,L) → (out,L)
    let conv =
        |x: &[f32], in_c: usize, out_c: usize, k: usize, dil: usize, w: &[f32]| -> Vec<f32> {
            let pad = same_pad(k, dil) as isize;
            let mut y = vec![0f32; out_c * l];
            for o in 0..out_c {
                for t in 0..l {
                    let mut acc = 0f32;
                    for ci in 0..in_c {
                        for j in 0..k {
                            let p = t as isize + (j as isize) * dil as isize - pad;
                            if p >= 0 && (p as usize) < l {
                                acc += w[(o * in_c + ci) * k + j] * x[ci * l + p as usize];
                            }
                        }
                    }
                    y[o * l + t] = acc;
                }
            }
            y
        };
    // batchnorm inference (per channel) in place
    let bn = |x: &mut [f32], c: usize, gamma: &[f32], beta: &[f32], mean: &[f32], var: &[f32]| {
        for ch in 0..c {
            let scale = gamma[ch] / (var[ch] + BN_EPS).sqrt();
            for t in 0..l {
                x[ch * l + t] = (x[ch * l + t] - mean[ch]) * scale + beta[ch];
            }
        }
    };
    let relu = |x: &mut [f32]| x.iter_mut().for_each(|v| *v = v.max(0.0));
    // squeeze-excitation (per channel scale) in place. fc1:[c,mid], fc2:[mid,c]
    let se = |x: &mut [f32], c: usize, fc1: &[f32], fc2: &[f32]| {
        let mid = se_mid(c);
        let mut s = vec![0f32; c];
        for ch in 0..c {
            let mut acc = 0f32;
            for t in 0..l {
                acc += x[ch * l + t];
            }
            s[ch] = acc / l as f32;
        }
        let mut e1 = vec![0f32; mid];
        for m in 0..mid {
            let mut acc = 0f32;
            for ch in 0..c {
                acc += s[ch] * fc1[ch * mid + m];
            }
            e1[m] = acc.max(0.0); // ReLU
        }
        for ch in 0..c {
            let mut acc = 0f32;
            for m in 0..mid {
                acc += e1[m] * fc2[m * c + ch];
            }
            let gate = 1.0 / (1.0 + (-acc).exp()); // sigmoid
            for t in 0..l {
                x[ch * l + t] *= gate;
            }
        }
    };

    // one residual block: conv→bn→(+skip|identity)→relu  (+SE)
    let block = |x: &[f32], in_c: usize, out_c: usize, dil: usize, i: usize| -> Vec<f32> {
        let mut main = conv(
            x,
            in_c,
            out_c,
            3,
            dil,
            &get(&format!("encoder.block{i}.conv.weight")).data,
        );
        bn(
            &mut main,
            out_c,
            &get(&format!("encoder.block{i}.bn.gamma")).data,
            &get(&format!("encoder.block{i}.bn.beta")).data,
            &get(&format!("encoder.block{i}.bn.running_mean")).data,
            &get(&format!("encoder.block{i}.bn.running_var")).data,
        );
        let identity = if in_c != out_c {
            conv(
                x,
                in_c,
                out_c,
                1,
                1,
                &get(&format!("encoder.block{i}.skip.weight")).data,
            )
        } else {
            x.to_vec()
        };
        for idx in 0..out_c * l {
            main[idx] += identity[idx];
        }
        relu(&mut main);
        se(
            &mut main,
            out_c,
            &get(&format!("encoder.se{i}.fc1.weight")).data,
            &get(&format!("encoder.se{i}.fc2.weight")).data,
        );
        main
    };

    let x = block(input, n_features, c1, 1, 1);
    let x = block(&x, c1, c2, 2, 2);
    let x = block(&x, c2, emb, 4, 3);
    let x = block(&x, emb, emb, 8, 4);

    // dual global pool over time → (2*emb) → pool_proj → relu
    let mut pooled = vec![0f32; emb * 2];
    for ch in 0..emb {
        let mut sum = 0f32;
        let mut mx = f32::NEG_INFINITY;
        for t in 0..l {
            let v = x[ch * l + t];
            sum += v;
            mx = mx.max(v);
        }
        pooled[ch] = sum / l as f32;
        pooled[emb + ch] = mx;
    }
    let proj_w = &get("encoder.pool_proj.weight").data; // [2*emb, emb]
    let mut embedding = vec![0f32; emb];
    for o in 0..emb {
        let mut acc = 0f32;
        for i in 0..emb * 2 {
            acc += pooled[i] * proj_w[i * emb + o];
        }
        embedding[o] = acc.max(0.0); // ReLU
    }

    embedding
}

/// Independent raw-`f32` reference logits for one `(n_features, window)` sample.
/// Cross-checks [`PerAssetCnn`]; also the executable spec a PyTorch golden must
/// satisfy.
pub fn reference_logits(weights: &WeightMap, input: &[f32], cfg: &PerAssetCnnConfig) -> Vec<f32> {
    let map: HashMap<&str, &SerializedTensor> =
        weights.iter().map(|st| (st.name.as_str(), st)).collect();
    let embedding = reference_encoder(&map, input, cfg.n_features, cfg.window, cfg.embedding_dim);
    let get = |name: &str| -> &SerializedTensor {
        map.get(name)
            .unwrap_or_else(|| panic!("missing weight {name}"))
    };
    let emb = cfg.embedding_dim;

    // head: Linear(emb→32) → relu → Linear(32→n_classes)
    let (w1, b1) = (&get("head.fc1.weight").data, &get("head.fc1.bias").data); // [emb,32]
    let mut hidden = [0f32; 32];
    for o in 0..32 {
        let mut acc = b1[o];
        for i in 0..emb {
            acc += embedding[i] * w1[i * 32 + o];
        }
        hidden[o] = acc.max(0.0);
    }
    let (w2, b2) = (&get("head.fc2.weight").data, &get("head.fc2.bias").data); // [32,n_classes]
    let mut logits = vec![0f32; cfg.n_classes];
    for o in 0..cfg.n_classes {
        let mut acc = b2[o];
        for i in 0..32 {
            acc += hidden[i] * w2[i * cfg.n_classes + o];
        }
        logits[o] = acc;
    }
    logits
}

